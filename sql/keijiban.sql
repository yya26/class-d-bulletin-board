DROP TABLE replies CASCADE CONSTRAINTS;
DROP TABLE threads CASCADE CONSTRAINTS;
DROP TABLE categories CASCADE CONSTRAINTS;

CREATE TABLE categories (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(50) NOT NULL
);


CREATE TABLE threads (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id NUMBER,
  title VARCHAR2(200) NOT NULL,
  author_name VARCHAR2(100),
  content CLOB,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  updated_at TIMESTAMP
);


ALTER TABLE threads
  ADD CONSTRAINT fk_category
  FOREIGN KEY (category_id)
  REFERENCES categories(id)
  ON DELETE SET NULL;


CREATE TABLE replies (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id NUMBER NOT NULL,
  author_name VARCHAR2(100),
  content CLOB,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);


ALTER TABLE replies
  ADD CONSTRAINT fk_thread
  FOREIGN KEY (thread_id)
  REFERENCES threads(id)
  ON DELETE CASCADE;


CREATE INDEX idx_threads_category ON threads(category_id);
CREATE INDEX idx_replies_thread ON replies(thread_id);


